export const LANGUAGES = [
  { code: 'en', label: 'English', native: 'English', dir: 'ltr' },
  { code: 'fr', label: 'Français', native: 'Français', dir: 'ltr' },
  { code: 'ar', label: 'العربية', native: 'العربية', dir: 'rtl' },
];

const LOCALES = { en: 'en-GB', fr: 'fr-FR', ar: 'ar-TN-u-nu-latn' };

let current = 'en';

export function setLanguage(code) {
  current = DICTIONARIES[code] ? code : 'en';
}

export function getLanguage() {
  return current;
}

export function isRTL() {
  return current === 'ar';
}

export function direction() {
  return isRTL() ? 'rtl' : 'ltr';
}

export function locale() {
  return LOCALES[current] || 'en-GB';
}

/** Translate a key, substituting `{name}` placeholders. */
export function t(key, vars) {
  const dict = DICTIONARIES[current] || DICTIONARIES.en;
  let value = dict[key];
  if (value === undefined) value = DICTIONARIES.en[key];
  if (value === undefined) return key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] === undefined ? match : String(vars[name]),
  );
}

export function hasKey(key) {
  return DICTIONARIES[current]?.[key] !== undefined;
}

const numberFormatCache = new Map();

export function number(value, options) {
  const key = `${current}:${JSON.stringify(options || {})}`;
  let fmt = numberFormatCache.get(key);
  if (!fmt) {
    fmt = new Intl.NumberFormat(locale(), options);
    numberFormatCache.set(key, fmt);
  }
  return fmt.format(value);
}

export function percent(value) {
  return new Intl.NumberFormat(locale(), {
    style: 'percent',
    maximumFractionDigits: value < 0.1 ? 1 : 0,
  }).format(value);
}

/**
 * Hijri (Umm al-Qura) date for a civil date, in the current language.
 * Falls back to an empty string on engines without the islamic calendar.
 */
export function hijriDate(iso) {
  try {
    return new Intl.DateTimeFormat(locale(), {
      calendar: 'islamic-umalqura',
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }).format(new Date(`${iso}T12:00:00Z`));
  } catch {
    return '';
  }
}

export function dateLong(iso) {
  return new Intl.DateTimeFormat(locale(), {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(new Date(`${iso}T12:00:00Z`));
}

export function dateMedium(iso) {
  return new Intl.DateTimeFormat(locale(), {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  }).format(new Date(`${iso}T12:00:00Z`));
}

export function dateShort(iso) {
  return new Intl.DateTimeFormat(locale(), {
    day: '2-digit',
    month: 'short',
  }).format(new Date(`${iso}T12:00:00Z`));
}

export function monthName(month, year) {
  return new Intl.DateTimeFormat(locale(), { month: 'long' }).format(
    new Date(Date.UTC(year || 2000, month - 1, 1, 12)),
  );
}

export function monthShort(month) {
  return new Intl.DateTimeFormat(locale(), { month: 'short' }).format(
    new Date(Date.UTC(2000, month - 1, 1, 12)),
  );
}

export function yearLabel(year) {
  return new Intl.NumberFormat(locale(), { useGrouping: false }).format(year);
}

export function weekdayNames() {
  const fmt = new Intl.DateTimeFormat(locale(), { weekday: 'short' });
  // 2023-01-01 was a Sunday.
  return Array.from({ length: 7 }, (_, i) => fmt.format(new Date(Date.UTC(2023, 0, 1 + i, 12))));
}

export function prayerLabel(key) {
  return t(`prayer.${key}`);
}

export function relativeDay(iso, todayIso) {
  if (iso === todayIso) return t('common.today');
  const diff = (Date.parse(`${iso}T00:00:00Z`) - Date.parse(`${todayIso}T00:00:00Z`)) / 86400000;
  if (diff === -1) return t('common.yesterday');
  if (diff === 1) return t('common.tomorrow');
  return dateMedium(iso);
}
